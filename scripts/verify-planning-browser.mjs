import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { parseEnv } from 'node:util'
import { createClient } from '@supabase/supabase-js'

// Real local catalogue, fresh browser storage, no API/database writes or accounts.
const env = parseEnv(readFileSync('.env.development.local', 'utf8'))
const api = new URL(env.NEXT_PUBLIC_SUPABASE_URL)
const app = new URL(process.env.TEST_APP_URL || 'http://127.0.0.1:3000')
for (const url of [api, app]) assert.ok(['127.0.0.1', 'localhost'].includes(url.hostname))
const db = createClient(api.href, env.NEXT_PUBLIC_SUPABASE_ANON_KEY, { auth: { persistSession: false } })
const { data: catalog, error } = await db.from('recipes').select('id,nom,saison').order('id')
assert.ifError(error)
const first = catalog.find(r => r.id === 'f85e95a0b4c2')
const second = catalog.find(r => r.id === '048c0c0fb076')
assert.ok(first && second, 'The original local Crous recipes must exist')
const title = r => r.nom.charAt(0).toUpperCase() + r.nom.slice(1)
const { chromium, devices } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true })
try {
  for (const [name, device] of [['desktop', { viewport: { width: 1440, height: 1000 } }], ['mobile', devices['Pixel 7']]]) {
    const context = await browser.newContext(device)
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => {
      if (message.type() === 'error' && !/Failed to load resource/.test(message.text())) errors.push(message.text())
    })
    await page.route('**/*', route => {
      const url = new URL(route.request().url())
      return ['127.0.0.1', 'localhost'].includes(url.hostname) ? route.continue() : route.abort()
    })
    const loaded = page.waitForResponse(r => r.url().includes('/rest/v1/recipes?') && r.ok())
    await page.goto(app.href)
    assert.equal((await (await loaded).json()).length, catalog.length)
    await page.getByRole('button', { name: 'Commencer', exact: true }).click()
    await page.getByRole('navigation').getByRole('button', { name: 'Planning', exact: true }).click()
    await page.getByRole('button', { name: 'Créer ma semaine', exact: true }).click()
    const resultItems = page.locator('section[aria-labelledby="recipe-results-title"] ul > li')
    assert.equal(await resultItems.count(), 20)
    await page.getByRole('button', { name: 'Afficher plus de recettes', exact: true }).click()
    assert.equal(await resultItems.count(), 40)
    const search = page.getByLabel('Rechercher une recette', { exact: true })
    await search.fill('  VEGETARIENNE BLANQUETTE  ')
    await page.getByRole('button', { name: `Choisir ${title(first)}`, exact: true }).waitFor()
    assert.equal(await page.getByRole('combobox').count(), 0, 'Optional filters start collapsed; no recipe dropdowns')
    assert.equal(await page.getByLabel('Temps maximum').isVisible(), false, 'Optional filters start collapsed')
    await page.getByText('Filtres (facultatifs)', { exact: true }).click()
    assert.equal(await page.getByRole('combobox').count(), 4)
    await page.getByLabel('Saison', { exact: false }).selectOption(first.saison)
    await page.getByRole('button', { name: `Choisir ${title(first)}`, exact: true }).waitFor()
    await page.getByLabel('Saison', { exact: false }).selectOption(first.saison === 'été' ? 'hiver' : 'été')
    await page.getByText(/Aucune recette trouvée/).waitFor()
    await page.getByRole('button', { name: 'Effacer la recherche et les filtres', exact: true }).click()
    await search.fill('aucun-plat-ne-porte-ce-nom-xyz')
    await page.getByText(/Aucune recette trouvée/).waitFor()
    await search.fill('blanquette vegetarienne')
    const days = page.getByLabel('Jours du planning').getByRole('button')
    await days.nth(2).click()
    await page.getByRole('button', { name: 'Choisir pour dîner', exact: true }).click()
    await page.getByRole('button', { name: `Voir la recette ${title(first)}`, exact: true }).click()
    const detail = page.getByRole('dialog')
    await detail.getByRole('heading', { name: 'Préparation', exact: true }).waitFor()
    const lastStep = detail.getByRole('button', { name: /Étape 8 :/ })
    assert.match(await lastStep.innerText(), /riz pendant 10 min/)
    await lastStep.focus()
    await page.keyboard.press('Space')
    assert.equal(await lastStep.getAttribute('aria-pressed'), 'true')
    assert.equal(await lastStep.locator('span').last().evaluate(el => getComputedStyle(el).textDecorationLine), 'none', 'Completed instructions stay readable')
    await page.keyboard.press('Escape')
    await detail.waitFor({ state: 'hidden' })
    await page.waitForFunction(label => document.activeElement?.getAttribute('aria-label') === label, `Voir la recette ${title(first)}`, { timeout: 3000 })
    await page.getByRole('button', { name: `Voir la recette ${title(first)}`, exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Ajouter au planning', exact: true }).click()
    await page.getByRole('heading', { name: 'Compose ta semaine', exact: true }).waitFor()
    assert.equal(await search.inputValue(), first.nom, 'The recipe sheet must open the manual editor with this dish')
    await days.nth(2).click()
    await page.getByRole('button', { name: 'Choisir pour dîner', exact: true }).click()
    await page.getByRole('button', { name: `Choisir ${title(first)}`, exact: true }).click()
    await page.getByText(/Blanquette végétarienne ajouté au dîner/).waitFor()
    assert.equal(await page.getByRole('button', { name: `Choisir ${title(first)}`, exact: true }).isDisabled(), true)
    await search.fill('galettes avoine')
    await page.getByRole('button', { name: `Voir la recette ${title(second)}`, exact: true }).click()
    await page.getByRole('dialog').getByText('Battre l’œuf dans un bol.', { exact: true }).waitFor()
    await page.getByRole('dialog').getByText('½ verre de flocons d’avoine', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Fermer la recette', exact: true }).click()
    await page.getByRole('button', { name: `Choisir ${title(second)}`, exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Annuler', exact: true }).click()
    let state = await page.evaluate(() => JSON.parse(localStorage.getItem('broco-chou-storage')).state)
    assert.equal(state.weeklyPlan.meals[0].recipeId, first.id, 'Cancel must preserve the previous dish')
    await page.getByRole('button', { name: `Choisir ${title(second)}`, exact: true }).click()
    await page.getByRole('button', { name: 'Confirmer le remplacement', exact: true }).click()
    await page.getByText(/ajouté en remplacement/).waitFor()
    await page.getByRole('button', { name: `Retirer ${title(second)} du dîner`, exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Retirer', exact: true }).click()
    await page.getByRole('button', { name: 'Annuler', exact: true }).click()
    await page.getByText(`Prévu : ${title(second)}`, { exact: true }).waitFor()
    await page.screenshot({ path: `supabase/.temp/planning-${name}.png`, fullPage: true })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No horizontal overflow')
    await page.getByRole('button', { name: 'Voir mon planning', exact: true }).click()
    await page.reload()
    await page.getByRole('navigation').getByRole('button', { name: 'Planning', exact: true }).click()
    state = await page.evaluate(() => JSON.parse(localStorage.getItem('broco-chou-storage')).state)
    assert.equal(state.weeklyPlan.meals.length, 1)
    assert.equal(state.weeklyPlan.meals[0].recipeId, second.id)
    assert.equal(state.weeklyPlan.meals[0].mealSlot, 'diner')
    const expectedDay = new Date(state.weeklyPlan.weekStart); expectedDay.setDate(expectedDay.getDate() + 2)
    assert.equal(new Date(state.weeklyPlan.meals[0].dayDate).getDate(), expectedDay.getDate())
    await page.getByRole('button', { name: 'Liste de courses', exact: true }).click()
    state = await page.evaluate(() => JSON.parse(localStorage.getItem('broco-chou-storage')).state)
    assert.ok(state.groceryList.some(item => item.name.includes('avoine')))
    assert.deepEqual(errors, [])
    console.log(`PASS ${name}: ${catalog.length} local recipes; accent/word search, filters, empty state, day/slot, full preparation, keyboard/focus, replacement/cancel, duplicate prevention, removal/undo, groceries, persistence and no horizontal overflow/JS errors.`)
    await context.close()
  }
} finally { await browser.close() }
