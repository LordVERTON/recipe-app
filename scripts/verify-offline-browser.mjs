import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { parseEnv } from 'node:util'
import { createClient } from '@supabase/supabase-js'

// Read only local configuration, and use a fresh browser profile/localStorage.
const env = parseEnv(readFileSync('.env.development.local', 'utf8'))
const api = new URL(env.NEXT_PUBLIC_SUPABASE_URL)
const app = new URL(process.env.TEST_APP_URL || 'http://localhost:3000')
for (const url of [api, app]) assert.ok(['127.0.0.1', 'localhost'].includes(url.hostname))
const db = createClient(api.href, env.NEXT_PUBLIC_SUPABASE_ANON_KEY, { auth: { persistSession: false, autoRefreshToken: false } })
const { data: recipes, error } = await db.from('recipes').select('id,nom,saison,estimated_time,image_url').order('id')
assert.ifError(error)
assert.ok(recipes.length > 0, 'Real local recipes required')
const target = recipes.find(recipe => recipe.image_url?.startsWith('https://images.pexels.com/'))
assert.ok(target, 'A real remote-photo recipe is required to test the fallback')
const { chromium, devices } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true })
try {
  const context = await browser.newContext(process.env.TEST_MOBILE === '1' ? devices['Pixel 7'] : { viewport: { width: 1440, height: 1000 } })
  const blocked = new Set(), errors = []
  await context.route('**/*', route => {
    const url = new URL(route.request().url())
    if (!['127.0.0.1', 'localhost'].includes(url.hostname)) { blocked.add(url.hostname); return route.abort('internetdisconnected') }
    return route.continue()
  })
  const page = await context.newPage()
  page.on('pageerror', error => errors.push(error.message))
  const catalogueResponse = page.waitForResponse(response => response.url().includes('/rest/v1/recipes?') && response.ok())
  await page.goto(app.href, { waitUntil: 'domcontentloaded' })
  const loaded = await (await catalogueResponse).json()
  assert.equal(loaded.length, recipes.length, 'UI must load the real local catalogue')
  await page.getByRole('button', { name: 'Commencer', exact: true }).click()
  await page.getByRole('navigation').getByRole('button').nth(1).click()
  await page.locator('button').filter({ has: page.locator('svg.lucide-star') }).last().click()
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('broco-chou-storage'))?.state.favoriteRecipes.length === 1)
  await page.getByRole('navigation').getByRole('button', { name: 'Planning', exact: true }).click()
  await page.getByRole('button', { name: 'Créer ma semaine', exact: true }).click()
  await page.getByLabel('Rechercher une recette', { exact: true }).fill(target.nom)
  const slot = page.getByRole('combobox', { name: 'Déjeuner', exact: true })
  await slot.locator(`option[value="${target.id}"]`).waitFor({ state: 'attached' })
  const seasonFilter = page.getByRole('combobox').nth(0)
  await seasonFilter.selectOption(target.saison)
  await slot.locator(`option[value="${target.id}"]`).waitFor({ state: 'attached' })
  const otherSeason = ['hiver', 'printemps', 'été', 'automne'].find(season => season !== target.saison)
  await seasonFilter.selectOption(otherSeason)
  assert.equal(await slot.locator(`option[value="${target.id}"]`).count(), 0, 'Season filter must exclude the recipe')
  await seasonFilter.selectOption('all')
  await slot.selectOption(target.id)
  await page.getByRole('button', { name: 'Voir mon planning', exact: true }).click()
  const image = page.getByRole('img', { name: new RegExp(target.nom.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'i') }).first()
  await image.waitFor()
  await page.waitForFunction(() => [...document.images].some(img => img.src.endsWith('/placeholder.jpg') && img.complete && img.naturalWidth > 0))
  assert.ok(blocked.has('images.pexels.com'), 'External photo requests must really be blocked')
  await image.click()
  await page.getByRole('heading', { name: 'Ingrédients', exact: true }).waitFor()
  await page.waitForFunction(() => [...document.images].filter(img => img.src.endsWith('/placeholder.jpg') && img.complete && img.naturalWidth > 0).length >= 2)
  await page.getByRole('button', { name: 'Fermer la recette', exact: true }).click()
  await page.getByRole('button', { name: 'Liste de courses', exact: true }).click()
  await page.getByRole('heading', { name: /courses/i }).first().waitFor()
  const persisted = await page.evaluate(() => JSON.parse(localStorage.getItem('broco-chou-storage')).state)
  assert.equal(persisted.weeklyPlan.meals[0].recipeId, target.id)
  assert.ok(persisted.groceryList.length > 0, 'Real local ingredients must populate groceries')
  await page.reload()
  await page.getByRole('navigation').waitFor()
  const reloaded = await page.evaluate(() => JSON.parse(localStorage.getItem('broco-chou-storage')).state)
  assert.equal(reloaded.weeklyPlan.meals[0].recipeId, target.id)
  assert.equal(reloaded.favoriteRecipes.length, 1)
  assert.deepEqual(errors, [])
  console.log(`PASS: ${recipes.length} real local recipes, swipe/favorite, search/season filters, manual plan, local photo fallback in calendar/detail, ingredients, groceries and reload; zero JS errors.`)
  console.log(`External traffic blocked in Chromium: ${[...blocked].join(', ') || '(none attempted)'}. This is not a physical WAN disconnect or a Docker network block.`)
} finally { await browser.close() }
