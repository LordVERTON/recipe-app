import { existsSync, mkdirSync, renameSync } from "node:fs"
import { spawnSync } from "node:child_process"
import path from "node:path"

const root = process.cwd()
const tempDirectory = path.join(root, "supabase", ".temp")
const backupDirectory = path.join(root, "supabase", ".local-start-link-backup")
const cli = path.join(root, "node_modules", "supabase", "bin", process.platform === "win32" ? "supabase.exe" : "supabase")
const linkedMetadata = ["project-ref", "linked-project.json", "pooler-url"]
const moved = []

try {
  // A linked project makes `supabase start` query Supabase Cloud for service
  // versions. Hide only the local link markers while starting; the original
  // files are restored immediately afterwards for remote workflows.
  mkdirSync(backupDirectory, { recursive: true })
  for (const filename of linkedMetadata) {
    const source = path.join(tempDirectory, filename)
    const backup = path.join(backupDirectory, filename)
    if (existsSync(source)) {
      if (existsSync(backup)) throw new Error(`Sauvegarde de liaison dÃ©jÃ  prÃ©sente : ${backup}`)
      renameSync(source, backup)
      moved.push({ source, backup })
    }
  }

  const result = spawnSync(cli, ["start"], {
    cwd: root,
    stdio: "inherit",
  })
  if (result.error) throw result.error
  process.exitCode = result.status ?? 1
} finally {
  for (const { source, backup } of moved.reverse()) {
    // Keep any marker generated by the local start separately instead of
    // overwriting it, then restore the user's remote link metadata.
    if (existsSync(source)) renameSync(source, `${source}.local-generated`)
    if (existsSync(backup)) renameSync(backup, source)
  }
}
